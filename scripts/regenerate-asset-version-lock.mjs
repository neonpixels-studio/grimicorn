import { existsSync, realpathSync, writeFileSync } from "node:fs";
import { resolve } from "node:path";
import { pathToFileURL } from "node:url";
import {
  ASSET_VERSION_LOCK_FILE,
  PROJECT_ROOT,
  SITE_WEBMANIFEST_FILE,
  assertTokenBumpedForChangedAssets,
  fingerprintAssets,
  parseAssetVersionLock,
  readAssetCacheBustToken,
  readAssetVersionLock,
  runGit,
  syncWebManifestCacheBustTokensOnDisk,
} from "../asset-version-manifest.mjs";

// Rewrites .vitepress/asset-version-lock.json from the current asset bytes and the
// live ASSET_CACHE_BUST token. Run whenever a versioned asset changes — but only after
// bumping the token, because the lock refuses to record changed bytes under an
// un-advanced token (that is the whole point of tying ?v= to content). Also syncs
// site.webmanifest's icon ?v= tokens to the live token before fingerprinting, so a
// token bump alone (no hand-edit of the manifest JSON) keeps it in sync.
const LOCK_DESCRIPTION =
  "Generated by scripts/regenerate-asset-version-lock.mjs — do not edit by hand. Maps each versioned asset to a sha256 of its bytes so a byte change without an ASSET_CACHE_BUST bump fails CI.";
const JSON_INDENT = 2;

// A first-lock or non-git checkout legitimately has no committed lock; any other git
// failure (git missing, broken repo) must NOT silently weaken the guard, so it rethrows.
// Deliberately looser than scripts/check-asset-version-bump.mjs's ABSENT_AT_REF_PATTERN:
// this also treats "unknown revision" (HEAD doesn't resolve yet, e.g. a brand-new repo
// with no commits) as "no lock", which the CI gate must NOT do — there HEAD always
// resolves, so "unknown revision" can only mean an unfetched base ref, a broken check
// that must fail loud. Relies on the shared runGit() (asset-version-manifest.mjs)
// pinning LC_ALL=C so this pattern isn't broken by a translated git.
const ABSENT_FROM_HEAD_PATTERN =
  /does not exist|exists on disk, but not in|unknown revision/;

// The baseline is the committed lock (HEAD), not the working-tree copy, so deleting or
// hand-editing the file on disk cannot slip a changed asset past the guard — the guard
// still compares against what is actually shipped in git.
function readCommittedLockOrNull() {
  let raw;
  try {
    raw = runGit(["show", `HEAD:${ASSET_VERSION_LOCK_FILE}`]);
  } catch (error) {
    const stderr = String(error.stderr ?? "");
    if (ABSENT_FROM_HEAD_PATTERN.test(stderr)) {
      return null;
    }
    throw new Error(
      `Could not read the committed lock from git: ${stderr.trim() || error.message}`,
      { cause: error },
    );
  }
  return parseAssetVersionLock(raw, `HEAD:${ASSET_VERSION_LOCK_FILE}`);
}

function readWorkingTreeLockOrNull() {
  if (!existsSync(resolve(PROJECT_ROOT, ASSET_VERSION_LOCK_FILE))) {
    return null;
  }
  return readAssetVersionLock();
}

function baselineLock() {
  return readCommittedLockOrNull() ?? readWorkingTreeLockOrNull();
}

// Runs `action`, restoring `manifestPath` to `previousManifestContents` if it throws.
// The manifest sync in regenerateLock() below writes to disk immediately, but
// validation can still reject the run (e.g. a reverted token bump) — without this,
// a rejected regen would leave the tracked manifest half-updated. A failure to
// restore is logged, not swallowed, so the *original* error is still what surfaces.
function withManifestRollback(manifestPath, previousManifestContents, action) {
  try {
    return action();
  } catch (error) {
    try {
      writeFileSync(manifestPath, previousManifestContents);
    } catch (restoreError) {
      console.error(
        `Failed to restore ${SITE_WEBMANIFEST_FILE} after a failed regen: ${restoreError.message}`,
      );
    }
    throw error;
  }
}

// token, manifestPath, lockPath, loadBaselineLock, and computeFingerprint default to
// the live ASSET_CACHE_BUST token, the real project files, and the real fingerprint
// sweep; tests override them to prove the sync-then-fingerprint ordering and the
// rollback path against throwaway fixtures instead of the committed manifest and
// lockfile.
export function regenerateLock({
  token = readAssetCacheBustToken(),
  manifestPath = resolve(PROJECT_ROOT, SITE_WEBMANIFEST_FILE),
  lockPath = resolve(PROJECT_ROOT, ASSET_VERSION_LOCK_FILE),
  loadBaselineLock = baselineLock,
  computeFingerprint = fingerprintAssets,
} = {}) {
  // Sync the manifest's ?v= tokens to the live token before fingerprinting, so the
  // hash recorded for site.webmanifest reflects synced bytes, not a JSON file a
  // contributor forgot to hand-edit after bumping ASSET_CACHE_BUST.
  const manifestBeforeSync = syncWebManifestCacheBustTokensOnDisk(
    token,
    manifestPath,
  );
  withManifestRollback(manifestPath, manifestBeforeSync, () => {
    const fingerprint = computeFingerprint();
    assertTokenBumpedForChangedAssets(loadBaselineLock(), token, fingerprint);
    const lock = {
      description: LOCK_DESCRIPTION,
      token,
      assets: fingerprint,
    };
    writeFileSync(lockPath, `${JSON.stringify(lock, null, JSON_INDENT)}\n`);
    console.log(`Wrote ${ASSET_VERSION_LOCK_FILE} for token ${token}.`);
  });
}

// Only run as a side effect when invoked directly (`node scripts/regenerate-asset-
// version-lock.mjs` / `npm run lock:assets`), not when imported — so the test suite
// can import regenerateLock() without triggering a real run against the repo.
// argv1 defaults to process.argv[1] but is overridable for tests. Node resolves
// symlinks when computing import.meta.url for the entry point, so argv1 must be
// realpath'd too — otherwise invoking through any symlinked path (a `/tmp` that is
// itself a symlink, as on macOS; a linked package bin) makes the two URLs disagree,
// isMainModule() returns false, and the script exits 0 having silently done nothing.
export function isMainModule(argv1 = process.argv[1]) {
  if (argv1 == null) {
    return false;
  }
  return import.meta.url === pathToFileURL(realpathSync(argv1)).href;
}

if (isMainModule()) {
  try {
    regenerateLock();
  } catch (error) {
    console.error(
      error instanceof Error ? (error.stack ?? error.message) : error,
    );
    process.exit(1);
  }
}
